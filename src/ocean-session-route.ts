import { randomBytes } from "node:crypto";
import { Hono } from "hono";
import { bodyLimit } from "hono/body-limit";
import { z } from "zod";
import type { CollectionRepository } from "./collection-contract.js";
import { isPlayerId } from "./collection-contract.js";
import { isFishSpeciesId } from "./fish-species.js";
import type { Waterway } from "./waterway.js";
import { accessHost } from "./ocean-host.js";
import { createPlayerSessionToken, hashPlayerSessionToken, readPlayerSessionToken } from "./player-session.js";
import { RequestRateLimiter } from "./request-rate-limit.js";

const sessionBodySchema = z.object({ playerId: z.string().refine(isPlayerId).optional() }).strict();
const oceanSessionBodySchema = z.object({ fishId: z.string().optional(), waterway: z.enum(["sea", "river"]).optional() }).strict();
const windowMs = 10 * 60_000;

const sourceFor = (request: Request): string =>
  request.headers.get("x-forwarded-for")?.split(",")[0]?.trim() || "unknown";

const rateLimited = (c: { header(name: string, value: string): void; json(value: unknown, status: number): Response }, retryAfter: number) => {
  c.header("Retry-After", String(retryAfter));
  return c.json({ error: "rate_limited" }, 429);
};

export function registerOceanSessionRoutes(
  app: Hono,
  options: { rooms: { createRoom(playerId: string, fishId?: string, waterway?: Waterway): string | undefined }; repository: Pick<CollectionRepository, "registerPlayerSession" | "getPlayerIdForSession" | "getCollection"> },
): void {
  const playerSessionLimiter = new RequestRateLimiter();
  const roomAttemptLimiter = new RequestRateLimiter();
  const roomCreationLimiter = new RequestRateLimiter();

  app.get("/api/collection", async c => {
    c.header("Cache-Control", "no-store");
    const token = readPlayerSessionToken(c.req.header("authorization"));
    if (!token) return c.json({ error: "unauthorized" }, 401);
    const playerId = await options.repository.getPlayerIdForSession(hashPlayerSessionToken(token));
    if (!playerId) return c.json({ error: "unauthorized" }, 401);
    return c.json(await options.repository.getCollection(playerId));
  });

  app.use("/api/player-sessions", bodyLimit({ maxSize: 1024 }));
  app.post("/api/player-sessions", async c => {
    const contentType = (c.req.header("content-type") ?? "").split(";", 1)[0]?.trim().toLowerCase();
    if (contentType !== "application/json") return c.json({ error: "unsupported_media_type" }, 415);

    const source = sourceFor(c.req.raw);
    const retryAfter = playerSessionLimiter.consume([
      { key: "global", limit: 600, windowMs },
      { key: `source:${source}`, limit: 120, windowMs },
    ]);
    if (retryAfter) return rateLimited(c, retryAfter);

    const parsed = sessionBodySchema.safeParse(await c.req.json().catch(() => null));
    if (!parsed.success) return c.json({ error: "invalid_player_session" }, 400);

    // Existing anonymous IDs are adopted once so the current browser keeps its
    // collection. New identities are generated by the server.
    const playerId = parsed.data.playerId ?? `player_${randomBytes(16).toString("hex")}`;
    const token = createPlayerSessionToken();
    const registered = await options.repository.registerPlayerSession(playerId, hashPlayerSessionToken(token));
    if (!registered) return c.json({ error: "player_session_exists" }, 409);

    c.header("Cache-Control", "no-store");
    return c.json({ playerId, token }, 201);
  });

  app.use("/api/ocean-sessions", bodyLimit({ maxSize: 1024 }));
  app.post("/api/ocean-sessions", async c => {
    const contentType = (c.req.header("content-type") ?? "").split(";", 1)[0]?.trim().toLowerCase();
    if (contentType !== "application/json") return c.json({ error: "unsupported_media_type" }, 415);

    const token = readPlayerSessionToken(c.req.header("authorization"));
    if (!token) return c.json({ error: "unauthorized" }, 401);
    const playerId = await options.repository.getPlayerIdForSession(hashPlayerSessionToken(token));
    if (!playerId) return c.json({ error: "unauthorized" }, 401);

    const source = sourceFor(c.req.raw);
    const attemptRetryAfter = roomAttemptLimiter.consume([
      { key: "global", limit: 1200, windowMs },
      { key: `source:${source}`, limit: 240, windowMs },
    ]);
    if (attemptRetryAfter) return rateLimited(c, attemptRetryAfter);

    const parsed = oceanSessionBodySchema.safeParse(await c.req.json().catch(() => null));
    if (!parsed.success) return c.json({ error: "invalid_ocean_session" }, 400);
    if (parsed.data.fishId && !isFishSpeciesId(parsed.data.fishId)) return c.json({ error: "invalid_fish_id" }, 400);

    const retryAfter = roomCreationLimiter.consume([
      // Leave room for a workshop or judging group sharing one NAT address.
      // The room-capacity guard below remains the hard resource limit.
      { key: "global", limit: 600, windowMs },
      { key: `source:${source}`, limit: 120, windowMs },
    ]);
    if (retryAfter) {
      console.warn(`[ocean] session creation rate limited; retryAfter=${retryAfter}s`);
      return rateLimited(c, retryAfter);
    }

    const id = options.rooms.createRoom(playerId, parsed.data.fishId, parsed.data.waterway ?? "sea");
    if (!id) return c.json({ error: "rooms_full" }, 503);
    c.header("Cache-Control", "no-store");
    return c.json({ id, host: accessHost(c.req.url) }, 201);
  });
}
